#!/usr/bin/env node
// Regenerates the LIVE table in docs/PEEVE-LIST.md from the actual files in
// src/peeves/, so the doc can never drift from what's deployed.
//
// It only ever rewrites the block between the two marker comments. Everything
// else in that file—notably the hand-written backlog of ideas that have no
// page yet—is preserved byte for byte. Adding a row to the backlog by hand is
// safe; this will not touch it.
//
// Run directly (`npm run list`) or let `npm run build` do it.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PEEVES = path.join(ROOT, "src", "peeves");
const DOC = path.join(ROOT, "docs", "PEEVE-LIST.md");

const BEGIN = "<!-- BEGIN:LIVE -->";
const END = "<!-- END:LIVE -->";

// Deliberately hand-rolled rather than pulling in a YAML dependency: the front
// matter here is flat scalars plus two simple lists, and a parser that only
// handles what this project writes is easier to trust than one that handles
// everything.
function frontMatter(raw) {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return null;
  const data = {};
  let listKey = null;
  for (const line of m[1].split(/\r?\n/)) {
    const item = line.match(/^\s+-\s+(.*)$/);
    if (item && listKey) {
      // Skip the nested mappings under `examples:`—only `aliases:` matters here.
      if (listKey === "aliases") data.aliases.push(item[1].trim());
      continue;
    }
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (!kv) continue;
    const [, key, rest] = kv;
    if (rest === "") {
      listKey = key;
      if (key === "aliases") data.aliases = [];
      continue;
    }
    listKey = null;
    data[key] = rest.replace(/^"(.*)"$/, "$1").replace(/\\"/g, '"');
  }
  return data;
}

const rows = fs
  .readdirSync(PEEVES)
  .filter((f) => f.endsWith(".md"))
  .map((f) => {
    const data = frontMatter(fs.readFileSync(path.join(PEEVES, f), "utf8"));
    if (!data) throw new Error(`No front matter in src/peeves/${f}`);
    return {
      slug: f.replace(/\.md$/, ""),
      title: data.title || f,
      category: data.category || "Other",
      order: Number(data.order ?? 999),
      summary: data.summary || "",
      snark: data.snark || "",
      aliases: data.aliases || [],
    };
  })
  .sort((a, b) => a.order - b.order || a.title.localeCompare(b.title));

// Pipes would break the table; nothing uses them today but a future summary might.
const esc = (s) => s.replace(/\|/g, "\\|");

const byCategory = new Map();
for (const r of rows) {
  if (!byCategory.has(r.category)) byCategory.set(r.category, []);
  byCategory.get(r.category).push(r);
}

const out = [BEGIN, ""];
out.push(`_${rows.length} live pages. Generated by \`utils/gen-peeve-list.js\`—edit the Markdown in \`src/peeves/\`, not this table._`, "");
for (const [category, items] of byCategory) {
  out.push(`### ${category}`, "");
  out.push("| Name | URL | Also answers to | Snark |");
  out.push("| ---- | --- | --------------- | ----- |");
  for (const r of items) {
    const url = `[/${r.slug}](https://omgstop.org/${r.slug})`;
    const alias = r.aliases.length ? r.aliases.map((a) => `\`/${a}\``).join(", ") : "none";
    out.push(`| ${esc(r.title)} | ${url} | ${alias} | ${esc(r.snark)} |`);
  }
  out.push("");
}
out.push(END);

let doc = fs.existsSync(DOC) ? fs.readFileSync(DOC, "utf8") : "";
if (doc.includes(BEGIN) && doc.includes(END)) {
  doc = doc.replace(
    new RegExp(`${BEGIN}[\\s\\S]*?${END}`),
    out.join("\n")
  );
} else {
  // First run: keep whatever is already in the file as the backlog section.
  const existing = doc.trim();
  doc = [
    "# Peeve list",
    "",
    "Live pages are generated from `src/peeves/`. The backlog below is yours to edit by hand—the generator never touches it.",
    "",
    "## Live",
    "",
    out.join("\n"),
    "",
    "## Backlog",
    "",
    "Ideas without a page yet. Add rows freely; nothing here is overwritten.",
    "",
    existing || "| Name | Description | Snark | Slug(s) |\n| ---- | ----------- | ----- | ------- |",
    "",
  ].join("\n");
}

fs.writeFileSync(DOC, doc.replace(/\n{3,}/g, "\n\n"));
console.log(`PEEVE-LIST.md: ${rows.length} live pages across ${byCategory.size} categories`);
